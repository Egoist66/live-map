  const query = ref('')

  const activeCategoryId = ref<string>('all')

  /**
   * Категории с учётом поискового запроса.
   */
  const filtered = computed<ChatPresetCategory[]>(() => {
    const needle = query.value.trim().toLowerCase()

    const byCategory = activeCategoryId.value === 'all'
      ? categories.value
      : categories.value.filter((category) => category.id === activeCategoryId.value)

    if (needle === '') {
      return byCategory
    }

    const matched = byCategory
      .map((category) => {
        const items = category.items.filter((item) => item.toLowerCase().includes(needle))

        return { ...category, items }
      })
      .filter((category) => category.items.length > 0)

    return matched
  })

  /**
   * Общее число фраз в каталоге.
   */
  const totalCount = computed<number>(() => {
    let total = 0

    for (const category of categories.value) {
      total += category.items.length
    }

    return total
  })

  function setQuery(value: string): void {
    query.value = value
  }

  function setCategory(id: string): void {
    activeCategoryId.value = id
  }

  function reset(): void {
    query.value = ''
    activeCategoryId.value = 'all'
  }

  return {
    categories,
    query,
    activeCategoryId,
    filtered,
    totalCount,
    setQuery,
    setCategory,
    reset,
  }
